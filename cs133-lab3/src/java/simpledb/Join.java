package simpledb;

import java.util.*;

/**
 * The Join operator implements the relational join operation.
 */
public class Join extends Operator {

    private static final long serialVersionUID = 1L;

    private JoinPredicate pred;
    private TupleDesc td1;
    private TupleDesc td2;
    private TupleDesc tdFinal;
    private DbIterator child1Iter;
    private DbIterator child2Iter;
    private Tuple currentTuple;

    /**
     * Constructor. Accepts two children to join and the predicate to join them
     * on
     * 
     * @param p
     *            The predicate to use to join the children
     * @param child1
     *            Iterator for the left(outer) relation to join
     * @param child2
     *            Iterator for the right(inner) relation to join
     */
    public Join(JoinPredicate p, DbIterator child1, DbIterator child2) {
        pred = p;
        td1 = child1.getTupleDesc();
        td2 = child2.getTupleDesc();
        tdFinal = TupleDesc.merge(td1, td2);
        child1Iter = child1;
        child2Iter = child2;
        currentTuple = null;
    }

    public JoinPredicate getJoinPredicate() {
        return pred;
    }

    /**
     * @return
     *       the field name of join field1. Should be quantified by
     *       alias or table name. Can be taken from the appropriate child's TupleDesc.
     * */
    public String getJoinField1Name() {
        return td1.getFieldName(pred.getField1());
    }

    /**
     * @return
     *       the field name of join field2. Should be quantified by
     *       alias or table name. Can be taken from the appropriate child's TupleDesc.
     * */
    public String getJoinField2Name() {
        return td2.getFieldName(pred.getField2());
    }

    /**
     * Should return a TupleDesc that represents the schema for the joined tuples. 
     *@see simpledb.TupleDesc#merge(TupleDesc, TupleDesc) for possible
     *      implementation logic.
     */
    public TupleDesc getTupleDesc() {
        return tdFinal;
    }

    public void open() throws DbException, NoSuchElementException,
    TransactionAbortedException {
        super.open();
        child1Iter.open();
        child2Iter.open();
    }

    public void close() {
        child1Iter.close();
        child2Iter.close();
        super.close();
    }

    public void rewind() throws DbException, TransactionAbortedException {
        child1Iter.rewind();
        child2Iter.rewind();
    }

    /**
     * Returns the next tuple generated by the join, or null if there are no
     * more tuples. Logically, this is the next tuple in r1 cross r2 that
     * satisfies the join predicate. There are many possible implementations;
     * the simplest is a nested loops join.
     * <p>
     * Note that the tuples returned from this particular implementation of Join
     * are simply the concatenation of joining tuples from the left and right
     * relation. Therefore, if an equality predicate is used there will be two
     * copies of the join attribute in the results. (Removing such duplicate
     * columns can be done with an additional projection operator later on if needed.)
     * <p>
     * For example, if one tuple is {1,2,3} and the other tuple is {1,5,6},
     * joined on equality of the first column, then this returns {1,2,3,1,5,6}.
     * 
     * @return The next matching tuple.
     * @see JoinPredicate#filter
     */
    protected Tuple fetchNext() throws TransactionAbortedException, DbException {
        Tuple t1 = currentTuple;
        // Starting off case - currentTuple initialized to null
        if (currentTuple == null && child1Iter.hasNext()) {
            t1 = child1Iter.next();
        }

        // Keep looping through left tuples until we find one that works
        while (true) {
            // Loop through right tuples for this left tuple
            while (child2Iter.hasNext()) {
                Tuple t2 = child2Iter.next();
                if(pred.filter(t1, t2)) {
                    Tuple newTuple = new Tuple(tdFinal);
                    for (int i = 0; i < td1.numFields(); i++) {
                        newTuple.setField(i, t1.getField(i));
                    }
                    for (int i = 0; i < td2.numFields(); i++) {
                        newTuple.setField(i+td1.numFields(), t2.getField(i));
                    }
                    currentTuple = t1;
                    return newTuple;
                }
            }
            // Just finished reading tuples out of child2Iter, need to reset
            if (child1Iter.hasNext()) {
                t1 = child1Iter.next();
                child2Iter.rewind();
            } else {
                // Looped through the whole thing and found no matches
                currentTuple = null;
                return null;
            }
        }
    }

    /**
     * See Operator.java for additional notes
     */
    @Override
    public DbIterator[] getChildren() {
        return new DbIterator[]{child1Iter, child2Iter};
    }

    /**
     * See Operator.java for additional notes
     */
    @Override
    public void setChildren(DbIterator[] children) {
        child1Iter = children[0];
        child2Iter = children[1];
    }

}
